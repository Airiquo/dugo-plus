import re, subprocess, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_pages import extract_by_id, body_of

body = body_of('light/admin-dashboard.html')
sidebar = extract_by_id(body, 'sidebar')
print("=== NAV LINKS ===")
for m in re.finditer(r'<a id="(nav-[^"]+)"[^>]*href="([^"]*)"[^>]*>(.*?)</a>', sidebar, re.S):
    label = re.findall(r'<span>([^<]*)</span>', m.group(3))
    badge = re.findall(r'className="badge"[^>]*>([^<]*)<', m.group(3))
    active = re.search(r'data-active="([^"]*)"', m.group(0))
    print(f'  {m.group(1):22s} active={active.group(1):5s} -> {m.group(2):30s} label={label} badge={badge}')

print()
print("=== SIDEBAR SKELETON ===")
print(re.sub(r'>[^<]+<', '><', sidebar)[:1500])
print()
print("=== SIDEBAR TAIL (after nav) ===")
nav_end = sidebar.index('</nav>') + len('</nav>')
print(re.sub(r'>[^<]+<', '><', sidebar[nav_end:])[:1500])
print()
topbar = extract_by_id(body, 'topbar')
print("=== TOPBAR SKELETON ===")
print(re.sub(r'>[^<]+<', '><', topbar))
print()
print("=== TOPBAR profile text ===")
print(re.findall(r'<span id="topbar-profile-text">.*?</span></span>', topbar, re.S))
print()
print("=== OVERLAY/TOAST roots in app-shell ===")
shell = extract_by_id(body, 'app-shell')
print([m.group(0) for m in re.finditer(r'<div id="(overlay|toast)-root"[^>]*>', shell)])
print()
print("=== PAGE HEADER (title/tag/actions) ===")
page = extract_by_id(body, 'page-content')
print(re.sub(r'>[^<]+<', '><', extract_by_id(page, 'page-header'))[:800])

import assert from 'node:assert/strict'
import { createServer } from '../../web/node_modules/vite/dist/node/index.js'
import { fileURLToPath } from 'node:url'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const server = await createServer({ configFile: fileURLToPath(new URL('./vite.config.mjs', import.meta.url)), configLoader: 'native' })
await server.listen()
const browser = await chromium.launch({...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {}),headless:true})
const context = await browser.newContext({viewport:{width:1280,height:900}})
const page = await context.newPage()
const errors=[]
page.on('pageerror',error=>errors.push(error.message))
await page.route('https://**/*',route=>route.abort())
const base=server.resolvedUrls.local[0].replace(/\/$/,'')
const dialog=page.getByRole('dialog',{name:'Log out of Dugo+?'})
async function at(path) { await page.waitForURL(base+path); }
async function backAndStay(path) {
  await page.evaluate(()=>history.back())
  await dialog.waitFor({state:'visible'})
  await at(path)
  await dialog.getByRole('button',{name:'Stay signed in',exact:true}).click()
  await dialog.waitFor({state:'hidden'})
  await at(path)
}
async function login(role) {
  await page.getByPlaceholder('name@email.com').fill(role+'@example.test')
  await page.getByPlaceholder('••••••••').fill('Password123')
  await page.getByRole('button',{name:'Sign In',exact:true}).click()
  await at(role==='admin'?'/admin/dashboard':role==='hospital'?'/hospital/dashboard':role==='unverified'?'/verify-email':'/donor/settings')
}
